/**
 * 解锁状态的**服务端单一来源**（2026-10-31，§72）
 *
 * ## 为什么要挪到服务端（实测踩到的语义错位）
 * 旧实现把"本次启动内已解锁"记在**浏览器页面**里（sessionStorage + 页面模块变量），
 * 但"一次运行"指的是 **EXE 进程的生命周期**，不是某个网页标签页的生命周期：
 * 用户关闭网页（EXE 仍在运行）再打开 ⇒ 页面模块变量随标签页销毁、sessionStorage 也是标签页级的
 * ⇒ 状态被重置回"未触发"，与"运行期间都是彩蛋触发后的效果"的口径相悖。
 * 服务端（与 launcher 同进程）才是"程序还在运行"的**真身** ⇒ 状态放这里：
 * 关网页 / 刷新 / 换浏览器都不丢，**重启软件自动归零**（新一轮运行重新拦截）。
 *
 * ⚠️ 这层是**伪装/彩蛋**，不是安全边界 —— 真实数据仍由 token 与门禁保护。
 * 🔒 纯内存、不落盘：进程退出即忘，绝无"永久解锁"。
 */
let unlockedThisRun = false

/** 本次运行是否已触发过彩蛋（未触发 ⇒ 拦截生效） */
export const isUnlockedThisRun = (): boolean => unlockedThisRun

/** 作弊码命中时置位（幂等；只增不减，进程退出才归零） */
export const markUnlockedThisRun = (): void => {
  unlockedThisRun = true
}
